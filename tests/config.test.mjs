import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

test('settings preserve secrets, allocate isolated accounts, reload and never rebind an identity', async t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'maitian-settings-'));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  const file = path.join(dir, 'config.json');
  fs.writeFileSync(file, JSON.stringify({ rootPath: dir, chromeProfile: path.join(dir, 'chrome'), web: { key: 'private-key' }, custom: 42 }));
  process.env.MAITIAN_CONFIG = file;
  const { config, saveSettings, bindBilibiliAccount, reloadConfig } = await import('../src/feishu.mjs');
  assert.equal(typeof saveSettings, 'function', 'settings persistence is missing');
  const view = saveSettings({ enabledPlatforms: ['bilibili'], bilibiliAccounts: [{ id: 'default', name: '主号', enabled: true }, { name: '副号', enabled: true }] });
  assert.equal(view.bilibiliAccounts.length, 2);
  const id = view.bilibiliAccounts[1].id;
  assert.match(id, /^[a-z0-9][a-z0-9_-]+$/);
  assert.equal(view.web, undefined);
  assert.equal(config.web.key, 'private-key');
  assert.equal(config.custom, 42);
  bindBilibiliAccount('default', '123', '示例账号');
  assert.equal(config.bilibiliAccounts[0].name, '示例账号');
  const { getTargets } = await import('../src/targets.mjs');
  assert.equal(getTargets(config)[0].name, 'B站 · 示例账号');
  bindBilibiliAccount('default', '123', '示例账号新昵称');
  assert.equal(config.bilibiliAccounts[0].name, '示例账号新昵称');
  bindBilibiliAccount(id, '456');
  assert.throws(() => bindBilibiliAccount(id, '789'), /身份|UID|账号/);
  const saved = JSON.parse(fs.readFileSync(file, 'utf8'));
  assert.equal(saved.bilibiliAccounts[1].uid, '456');
  assert.throws(() => saveSettings({ enabledPlatforms: ['bilibili'], bilibiliAccounts: [{ id: 'default', name: '主号', uid: '', enabled: true }, { id, name: '冒名', uid: '789', enabled: true }] }), /UID|身份|账号/);
  assert.throws(() => saveSettings({ enabledPlatforms: ['unknown'], bilibiliAccounts: [] }), /平台/);
  const before = fs.readFileSync(file, 'utf8');
  fs.writeFileSync(file + '.lock', String(process.pid));
  assert.throws(() => saveSettings({ enabledPlatforms: [], bilibiliAccounts: [] }), /修改|保存/);
  assert.equal(fs.readFileSync(file, 'utf8'), before);
  fs.unlinkSync(file + '.lock');
  const removed = saveSettings({ enabledPlatforms: ['bilibili'], bilibiliAccounts: [{ id: 'default', name: '主号', enabled: true }] });
  assert.equal(removed.bilibiliAccounts.length, 1);
  assert.deepEqual(getTargets(config).map(target => target.id), ['bilibili']);
  const afterRemoval = fs.readFileSync(file, 'utf8');
  assert.throws(() => saveSettings({ enabledPlatforms: ['bilibili'], bilibiliAccounts: [{ id: 'default', name: '<bad>', enabled: 'yes' }] }), /状态/);
  assert.equal(fs.readFileSync(file, 'utf8'), afterRemoval);
  fs.writeFileSync(file, JSON.stringify({ ...saved, enabledPlatforms: [] }));
  reloadConfig();
  assert.deepEqual(config.enabledPlatforms, []);
  const site = await import('../src/site.mjs');
  assert.equal(site.SITE, null);
  fs.writeFileSync(file, JSON.stringify({ ...saved, site: { base: 'https://example.com', name: '课程' }, enabledPlatforms: ['zsz'] }));
  reloadConfig();
  assert.equal(site.SITE?.name, '课程');
  fs.writeFileSync(file, JSON.stringify({ ...saved, enabledPlatforms: [] }));
  reloadConfig();
  assert.equal(site.SITE, null);
  assert.deepEqual(fs.readdirSync(dir), ['config.json']);
});
